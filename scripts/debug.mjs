import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
page.on('pageerror', e => console.log('PAGEERROR', String(e)))
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.waitForTimeout(500)
const board = await page.locator('.board').boundingBox()
const ids = await page.locator('.glyph').evaluateAll(n => n.map(e => e.getAttribute('data-id')))
console.log('glyphs', ids.length, 'board', board)
await page.locator('.glyph[data-id="0"]').click()
await page.waitForTimeout(300)
console.log('tiles after click', await page.locator('.tile').count())
const gb = await page.locator('.glyph[data-id="3"]').boundingBox()
console.log('glyph3 box', gb)
await page.mouse.move(gb.x + gb.width/2, gb.y + gb.height/2)
await page.mouse.down()
await page.mouse.move(board.x + board.width*0.55, board.y + board.height*0.8, { steps: 12 })
await page.waitForTimeout(200)
console.log('ghost?', await page.locator('.text-ghost').count())
await page.mouse.up()
await page.waitForTimeout(400)
console.log('tiles after drag', await page.locator('.tile').count())
console.log('holes', await page.locator('.hole').count())
await browser.close()
